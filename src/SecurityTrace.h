/*
 * NoC Sentinel - security configuration, compromised-node-aware routing
 * and per-packet evidence tracing for Noxim (MESH topology only).
 *
 * Configuration is read from environment variables (same mechanism as the
 * existing NOXIM_ATTACK / NOXIM_MAL_NODE / NOXIM_MITIGATE prototypes):
 *
 *   NOXIM_MAL_NODE      compromised node id (0 .. X*Y-1), -1/unset = none
 *   NOXIM_ATTACK        attack mode executed by the compromised router
 *   NOXIM_MITIGATE      1 = enable avoidance routing at all healthy routers
 *   NOXIM_SRC_POLICY    ALLOW | QUARANTINE  (default QUARANTINE)
 *                       packets generated BY the compromised node
 *   NOXIM_DST_POLICY    DELIVER | QUARANTINE | REMAP (default QUARANTINE)
 *                       packets whose logical destination IS the compromised node
 *   NOXIM_BACKUP_NODE   explicit backup endpoint, required for REMAP
 *                       (no automatic choice is made)
 *   NOXIM_TRACE_PREFIX  if set, writes <prefix>_packets.csv and <prefix>_hops.csv
 *   NOXIM_DECOUPLE_RNG  1 = router arbitration/selection no longer consume the
 *                       global rand() stream used by traffic generation, so runs
 *                       with identical seed inject identical traffic.
 *
 * Policies only take effect when NOXIM_MITIGATE=1.
 */

#ifndef __NOXIM_SECURITY_TRACE_H__
#define __NOXIM_SECURITY_TRACE_H__

#include <string>
#include "DataStructs.h"

namespace SecurityTrace {

void init();                    // call once after configuration is loaded
bool mitigationActive();
int malNode();
bool decoupleRng();
unsigned int localRand();

int neighborOf(int node, int dir);           // -1 if outside the mesh
int xyDirection(int current_id, int dst_id); // plain XY choice
// Avoidance route: returns a direction, or -1 when not applicable / unreachable.
int safeRoute(int current_id, int dst_id);

// Called by the PE when a packet is generated. Assigns packet_id, applies the
// source / destination policies. Returns true if the packet must be injected.
bool onPacketGenerated(Packet &p, double now_cycles);

void onHeadEnteredNetwork(const Flit &f, int router_id, double now);
void onForward(const Flit &f, int router_id, int out_dir, double now);
void onLocalConsume(const Flit &f, int router_id, double now);
void onAttackDrop(const Flit &f, int router_id, double now);
void onTamper(const Flit &f, int router_id, int old_dst, int new_dst, double now);

void exportAll();               // writes CSVs + prints a summary

}

#endif
